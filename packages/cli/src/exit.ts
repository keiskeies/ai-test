/**
 * 退出码表（M6：`atest` 要在 CI 里用，退出码就是它的 API）。
 *
 * 为什么不用 0/1 两个码就完事：CI 里"没跑成"与"跑出来是红的"必须能区分开，
 * 否则一个配置写错的构建和一个真失败的构建长得一模一样，
 * 而值班人对这两件事的动作完全不同。
 *
 * 更要紧的是**保留段**：npm/npx 会把子进程信号死亡转成 `128+signum`
 * （SIGINT=130、SIGKILL=137），`126/127` 是 shell 的"不可执行/找不到命令"。
 * 我们自己占这些码的话，"有人 Ctrl-C"会被流水线读成我们的某个业务结论 ——
 * 这种混淆一旦发生就查不出来，因为两边都"有理由"。
 *
 * 导出成表而不是散落的字面量：CLI 契约测试要能**遍历**它，
 * 断言没有码落在保留段里。写死的断言会在有人加一个 `= 130` 时无声通过。
 */
export const EXIT = {
  /** 全绿 */
  OK: 0,
  /** 跑通了，但有步骤 fail（= 测出了产品问题）。这是**好消息不是错误**，见 CI 建议 */
  TEST_FAILED: 1,
  /** 用法错（未知命令、未知开关、缺参数）。不跑任何东西 */
  USAGE: 2,
  /** IR 不合法 / lint 有 error / 场景没 frozen 却带 --ci */
  INVALID: 3,
  /** 环境缺失（baseUrl 没配、spec 文件读不到、--local 起 mock 失败） */
  ENV: 4,
  /** 运行本身出错（引擎抛异常、超时、成本超限） */
  RUNTIME: 5,
  /** 被信号打断（我们主动响应 SIGINT 时用这个；与 128+signum 的区别是"我清理干净了"） */
  ABORTED: 10,
} as const;

/**
 * 不得占用的退出码（见文件头）。CLI 契约测试逐条检查。
 *
 * 从 64 起整段也算保留，但**当前没在用**。记在这里是因为 shell 世界对高码段有约定：
 * `xargs` 用 123、`grep` 用 2、`sed`/`awk` 的 `exit N` 会绕回 0–255 —— 更要紧的是
 * **一些 CI runner 把 >125 的码当成"基础设施异常"而不是"构建失败"**（不标红、不通知人），
 * 所以 `ABORTED = 10` 特意落在低段。要加新码，只在 6–63 之间取，同时补进上面那张表。
 */
export const RESERVED_EXIT: readonly number[] = [126, 127, 128, 130, 137, 139];

