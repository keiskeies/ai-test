/**
 * 给"用正则读 IR 源码文本"那几条测试用的**同一个**文本预处理。
 *
 * ## 为什么要有这个文件
 *
 * `expr-fields.test.ts` 与 `wait-expr-fields.test.ts` 都用正则从源码里找
 * `字段: ExprSchema`，用来独立核对 zod 派生出来的那张表（两个来源对不上才有信息量，
 * 拿派生表跟另一份手抄清单比是同义反复）。
 *
 * **而正则是哑的，它读不出"这行是代码还是这段是散文"** —— 本轮就撞上了：
 * 我在 `waits.ts` 新写的那段注释里举了一个**假想**的条件
 * `{type:'scalarTruth', exprEq: ExprSchema}`，正则把它当成真字段，于是
 * 报出 `源码里写着 ExprSchema 而派生表不认：newPage.exprEq`
 * （连类型都猜错了 —— 它把下一个 `type: z.literal(...)` 之前的一切算作上一个成员）。
 *
 * 这个假阳性**值得留着当例子**而不是把注释改掉：它证明了"扫源码文本"这条判据
 * 会被文档里的措辞影响，所以扫描必须先去掉注释，而且要去得**可自检**
 * （见 {@link stripComments}：剥完之后还要能认出已知字段，否则宁可直接红）。
 *
 * 反过来也要说清**这条判据因此弱在哪**：扫的是源码，注释不参与；
 * 而"往 schema 加了 ExprSchema 字段而派生表看不到"这件事仍然扫得出来，
 * 因为那处改动必然落在代码里。**没有变弱。**
 */

/** 去掉块注释与行注释。**不做字符串识别** —— 前提见下面那条自检。 */
export function stripComments(src: string): string {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}

/**
 * 剥注释这件事自己的自检。
 *
 * 两个方向都会坏，而且都是"静默不干活"那一类：
 *  - 剥**多**了（比如源码里出现了含 `//` 的字符串字面量、URL），真字段被吃掉，
 *    于是扫描扫不到任何东西、断言恒通过；
 *  - 剥**少**了（注释语法变了），假想字段又会被当成正字段。
 * 所以调用方在扫之前先拿几个**必然存在**的字段验一遍扫描本身。
 * 这里不用 URL 排除法（那是往一个哑判据上再叠一个哑判据），
 * 而是直接扫 IR 的两个源文件确认没有含 `//` 的字符串 —— 由
 * `src-text.test.ts` 里那条钉着；有那一天，这条自检会红，
 * 而红的时候要做的是把这里换成真正的 tokenizer，不是放宽断言。
 */
export function assertScannerWorks(strip: string, mustFind: readonly RegExp[]): void {
  for (const re of mustFind) {
    if (!re.test(strip)) {
      throw new Error(
        `扫描器自检失败：剥掉注释之后连 "${re.source}" 都认不出来了。`
        + '此时**不许放宽下面那组断言**，要改的是扫描器本身（大概遇上了含 // 的字符串字面量）。',
      );
    }
  }
}
